export function formatRelativeContact(dateStr) {
  if (!dateStr) return null;
  const date = new Date(dateStr);
  const now = new Date();
  const diffMs = now - date;
  const diffMins = Math.floor(diffMs / 60000);
  const diffHours = Math.floor(diffMs / 3600000);
  const diffDays = Math.floor(diffMs / 86400000);
  if (diffMins < 1) return 'Ahora';
  if (diffMins < 60) return `Hace ${diffMins}m`;
  if (diffHours < 24) return `Hace ${diffHours}h`;
  if (diffDays === 1) return 'Ayer';
  if (diffDays < 7) return `Hace ${diffDays}d`;
  return date.toLocaleDateString('es-AR', { day: 'numeric', month: 'short' });
}

// Iniciales a partir del nombre del asesor.
export function initialsFromName(name) {
  if (!name) return '?';
  return name.split(' ').map(w => w[0]).join('').slice(0, 2).toUpperCase();
}

export function buildWhatsAppUrl(phone) {
  if (!phone) return null;
  const cleanPhone = phone.replace(/[^\d+]/g, '');
  const whatsappPhone = cleanPhone.startsWith('+') ? cleanPhone : `+54${cleanPhone.replace(/^0/, '')}`;
  return `https://wa.me/${whatsappPhone}`;
}
